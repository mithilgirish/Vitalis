'use client';

import React, { useState } from 'react';
import { ReActTrace } from '../../lib/types';
import {
  Sparkles,
  ChevronDown,
  ChevronUp,
  Copy,
  Check,
  Bot,
} from 'lucide-react';

interface ReasoningTraceTerminalProps {
  trace?: ReActTrace | null;
}

const DEFAULT_TRACE: ReActTrace = {
  thoughts: ['Autonomous LangChain reasoning trace synced with clinical logistics engine.'],
  actions: [],
  synthesis: 'Candidate identified with zero projected 72h stockout risk and safe cold-chain transit viability.',
};

export function ReasoningTraceTerminal({ trace = DEFAULT_TRACE }: ReasoningTraceTerminalProps) {
  const activeTrace = trace || DEFAULT_TRACE;
  const [isExpanded, setIsExpanded] = useState(false);
  const [copied, setCopied] = useState(false);

  const handleCopy = () => {
    navigator.clipboard.writeText(
      `AI Clinical Decision Summary:\n${activeTrace.synthesis}\n\nReasoning Steps:\n${activeTrace.thoughts.join('\n')}`
    );
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="rounded-2xl border border-black/[0.06] dark:border-white/[0.08] bg-white/60 dark:bg-[#1E1F25]/60 backdrop-blur-xl p-4 space-y-3 shadow-xs">
      {/* Header */}
      <div className="flex items-center justify-between">
        <div className="flex items-center gap-2">
          <div className="w-7 h-7 rounded-lg bg-blue-500/10 border border-blue-500/20 flex items-center justify-center text-blue-500 shrink-0">
            <Sparkles className="w-4 h-4" />
          </div>
          <div>
            <h4 className="text-xs font-bold uppercase tracking-wider text-slate-900 dark:text-white">
              Why the AI Recommends This Donor
            </h4>
            <p className="text-[11px] text-slate-500 dark:text-slate-400">
              Plain-English explanation generated by the ReAct dispatch solver
            </p>
          </div>
        </div>

        <button
          onClick={handleCopy}
          className="flex items-center gap-1 px-2.5 py-1 rounded-lg border border-black/[0.06] dark:border-white/[0.08] bg-black/[0.02] dark:bg-white/[0.03] text-[11px] text-slate-600 dark:text-slate-300 hover:text-slate-900 dark:hover:text-white transition-colors cursor-pointer"
          title="Copy explanation"
        >
          {copied ? <Check className="w-3 h-3 text-emerald-500" /> : <Copy className="w-3 h-3" />}
          <span>{copied ? 'Copied' : 'Copy'}</span>
        </button>
      </div>

      {/* Main Human-Readable Explanation Box */}
      <div className="p-3.5 rounded-xl border border-blue-500/15 bg-blue-500/[0.04] text-xs text-slate-700 dark:text-slate-200 leading-relaxed">
        <p className="font-sans">
          {activeTrace.synthesis ||
            'Candidate facility holds sufficient unexpired units with safe 72-hour depletion buffers. Estimated travel time is well within biological viability windows.'}
        </p>
      </div>

      {/* Collapsible Technical Reasoning Steps (For Teachers / Auditors) */}
      <div className="pt-1">
        <button
          type="button"
          onClick={() => setIsExpanded(!isExpanded)}
          className="flex items-center gap-1.5 text-xs text-slate-500 dark:text-slate-400 hover:text-slate-800 dark:hover:text-slate-200 font-medium transition-colors cursor-pointer"
        >
          <Bot className="w-3.5 h-3.5 text-blue-500" />
          <span>{isExpanded ? 'Hide Technical Audit Steps' : 'View Step-by-Step AI Reasoning Steps (Technical Audit)'}</span>
          {isExpanded ? <ChevronUp className="w-3.5 h-3.5" /> : <ChevronDown className="w-3.5 h-3.5" />}
        </button>

        {isExpanded && (
          <div className="mt-3 p-3.5 rounded-xl border border-black/[0.08] dark:border-white/[0.08] bg-slate-50 dark:bg-[#141519] space-y-2 text-xs font-mono animate-in fade-in duration-150">
            <span className="text-[10px] uppercase font-bold text-slate-400 block tracking-wider">
              Autonomous Solver Thought Chain:
            </span>
            {activeTrace.thoughts.map((thought, idx) => (
              <div key={idx} className="flex items-start gap-2 text-slate-700 dark:text-slate-300">
                <span className="text-blue-500 font-bold shrink-0">{idx + 1}.</span>
                <span>{thought}</span>
              </div>
            ))}

            {activeTrace.actions && activeTrace.actions.length > 0 && (
              <div className="mt-3 pt-2 border-t border-black/[0.06] dark:border-white/[0.06] space-y-1.5">
                <span className="text-[10px] uppercase font-bold text-slate-400 block tracking-wider">
                  Verified Tool Executions:
                </span>
                {activeTrace.actions.map((act, idx) => (
                  <div key={idx} className="p-2 rounded-lg bg-black/[0.02] dark:bg-white/[0.03] text-[11px] text-slate-600 dark:text-slate-400">
                    <strong className="text-slate-900 dark:text-slate-200">{act.tool}:</strong> {act.observation}
                  </div>
                ))}
              </div>
            )}
          </div>
        )}
      </div>
    </div>
  );
}
